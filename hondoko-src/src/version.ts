export const USAGE_GUIDE = `【本ドコ？の使い方】

■ はじめに(初回セットアップ)
1. Googleアカウントでログイン
2. 「設定」タブで棚構成を確認(メイン IKEA-1〜6 / サブ1〜3 / 別室)。実際の本棚に合わせて名前や段数を編集できます

■ 画像マップ(v1.1〜)
1. 「マップ」タブ →「本棚の写真からマップを追加」で壁全体の写真をアップロード
2. 「領域編集」を押して、写真上をドラッグで段の範囲を囲む → 棚と段を割り当て
3. 本がある段は写真上でハイライトされ、タップするとその段のリストへ

■ 本の登録(おすすめ: 写真で一括登録)
1. 「マップ」タブで、段の横の「カメラ」ボタンをタップ(マップ写真の領域右下にもあります)
2. その段のクローズアップ写真を撮影(背表紙の文字が読める距離で)
3. 解析はバックグラウンドで実行(1〜2分)。その間ほかの操作をしてOK
4. 画面下のバーに「解析完了」と出たら「確認する」→ 内容をチェックして「反映」

・1枚の写真に2〜3段写っていてもOK。段ごとに分けて認識され、それぞれ割り当て先を選べます
・マップ写真に領域を設定済みなら「写真を撮って自動判別で登録」も使えます。
  どの段か指定しなくても、マップと照合してAIが場所を判定します

■ 差分検知(本を動かした/売った/買ったとき)
同じ段をもう一度撮影するだけ。前回登録した内容と比べて
「追加された本」「見当たらない本」「他の段から移動してきた本」を提案します。
確認して反映すればリストが最新になります。

■ 探す
「検索」タブでタイトル・著者・出版社・#タグを横断検索。
「著者:池上彰」「出版社:講談社」のようにフィールド指定もできます。
本を開くと「どの棚のどの段にあるか」と関連書籍が表示され、
著者・出版社・タグをタップするとそのまま検索できます。
書影は本を開いたときに自動取得されます(ISBN登録があるほど正確)。

■ 誤登録の整理(段ビュー)
段を開くと各本にチェックボックスがあります。全選択・Shift+クリックの範囲選択に対応。
選択して「削除」(完全削除)か「未配置にする」で一括整理できます。
PCではGmail準拠のショートカットが使えます:
  J/K=上下移動  X=選択  #=削除  E=未配置  Enter=開く  Esc=選択解除

■ 買い足した本の追加
「追加」タブ →「本の写真から追加」で新しい本だけを撮影(表紙でOK、複数冊可)。
AIが読み取ったあと、入れる棚・段を選んで追記します。段の再撮影は不要です。
段を開いて「本を追加」からなら、その段に直接追記できます。

■ その他の登録方法
・ISBNバーコードをカメラでスキャン(openBD/Google Booksから書誌取得)
・手動入力
・CSVインポート/エクスポート(バックアップにも)

■ 本の情報管理
本の詳細で 既読/未読の切り替え、★5段階評価、タグの追加・削除、
購入価格・想定売値の入力(メルカリ相場リンク付き)、Amazonレビューへのリンクが使えます。
コメント欄は家族やゲストとの共有メモに。

■ ゲストに見せる(公開設定)
設定タブ →「公開設定」で選べます:
・メンバーのみ(標準) ・特定の人のみ(メールで指定)
・リンクを知っている人(キー付きURL) ・公開
ゲストは閲覧専用(Googleログインが必要)。コメント投稿の許可も選べます。

■ コツ
・写真は1段ずつ、正面から、明るい場所で
・シリーズ物も1冊ずつ認識されます
・AIの読み取りは完璧ではないので、確認画面で修正してから反映してください`
